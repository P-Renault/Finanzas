drop policy if exists "fuentes_ingreso_update" on public.fuentes_ingreso;
create policy "fuentes_ingreso_update" on public.fuentes_ingreso for update to anon, authenticated using (true) with check (true);

drop policy if exists "generacion_ingresos_select" on public.generacion_ingresos;
create policy "generacion_ingresos_select" on public.generacion_ingresos for select to anon, authenticated using (true);
drop policy if exists "generacion_ingresos_insert" on public.generacion_ingresos;
create policy "generacion_ingresos_insert" on public.generacion_ingresos for insert to anon, authenticated with check (true);
drop policy if exists "generacion_ingresos_update" on public.generacion_ingresos;
create policy "generacion_ingresos_update" on public.generacion_ingresos for update to anon, authenticated using (true) with check (true);
