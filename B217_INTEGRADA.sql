-- NO crea ni modifica jornadas_financieras.
-- NO elimina datos históricos.

create table if not exists public.fuentes_ingreso (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  tipo text not null check (tipo in ('plataforma','servicio','emprendimiento','ecommerce','otro')),
  activa boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.generacion_ingresos (
  id bigint generated by default as identity primary key,
  fuente_id bigint not null references public.fuentes_ingreso(id),
  actividad text not null,
  descripcion text,
  cliente text,
  fecha_generacion date not null,
  fecha_cobro date,
  monto_bruto numeric(12,2) not null default 0 check (monto_bruto >= 0),
  costos numeric(12,2) not null default 0 check (costos >= 0),
  comisiones numeric(12,2) not null default 0 check (comisiones >= 0),
  monto_neto numeric(12,2) generated always as (greatest(monto_bruto-costos-comisiones,0)) stored,
  estado_cobro text not null default 'pendiente' check (estado_cobro in ('pendiente','cobrado','cancelado')),
  movimiento_id bigint references public.movimientos(id),
  notas text,
  created_at timestamptz not null default now()
);

create index if not exists generacion_ingresos_fecha_idx on public.generacion_ingresos(fecha_generacion);
create index if not exists generacion_ingresos_cobro_idx on public.generacion_ingresos(fecha_cobro);
create index if not exists generacion_ingresos_fuente_idx on public.generacion_ingresos(fuente_id);

